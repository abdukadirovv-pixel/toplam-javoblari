def get_answer(year: str, group: str, q: int):
    """Return 'A'..'E', or None if not found."""
    g = ANSWERS.get(year, {}).get(group)
    if g is None or q < 1:
        return None
    rows = g.split()
    r, c = divmod(q, 10)
    if r >= len(rows) or c >= len(rows[r]):
        return None
    ch = rows[r][c]
    return None if ch == "-" else ch


def group_size(year: str, group: str):
    g = ANSWERS.get(year, {}).get(group)
    if not g:
        return 0
    rows = g.split()
    return (len(rows) - 1) * 10 + len(rows[-1]) - 1
